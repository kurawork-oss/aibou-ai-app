/**
 * はじめる手順（初回設定）。
 *
 * ここはフロント側に置いてある。理由:
 *   この手順は「まだ何も繋がっていない人」が読むもの。バックエンドから
 *   取ってくる作りにしていたため、繋がっていないと手順そのものが消え、
 *   「自分のDBを繋ぎたいのに、繋ぎ方がどこにも書いていない」状態になった。
 *   繋がる前に必要な案内を、繋がらないと読めない場所に置いてはいけない。
 *
 * 貼り付けるSQLは public/supabase_schema.sql をそのまま配信する
 * （本文に書き写すと、本物のスキーマと必ずズレる）。
 *
 * 書くときの決まり
 *   ・押すボタンの文言、成功したときの表示まで書く
 *   ・つまずくところは先回りして書く（あとで問い合わせになる）
 */

export interface SetupStep {
  id: string;
  title: string;
  /**
   * ひとことで言うと何をするのか。専門用語を使わない例えで書く。
   * 「Supabaseを作る」と言われても、何をさせられるのか分からない人向け。
   */
  plain: string;
  /** かかる時間の目安。先に分かると身構えずに済む。 */
  minutes: string;
  /** なぜ必要か。意味が分かると間違えにくい。 */
  detail?: string;
  /** 実際の操作。見たままの文言で。 */
  steps: string[];
  /** 貼り付けるものを、この場所から取ってくる。 */
  codeUrl?: string;
  codeLabel?: string;
  /** つまずきどころ・やってはいけないこと。 */
  caution?: string[];
}

/**
 * 用語のいいかえ。
 *
 * 画面や外部サービスには英語の名前がそのまま出るので、言葉自体は消せない。
 * 消せない代わりに、そのつど「要するに何か」を並べて置く。
 */
