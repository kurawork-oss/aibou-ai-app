/**
 * その発言を、長期記憶に入れるかどうか。
 *
 * なぜ要るのか
 * ------------
 * これまでは、話しかけた文を**全部そのまま**覚えていた。会話には
 * 「うん」「ありがとう」「これ直して」「どう？」が大量にあるので、
 * 長期記憶がそれで埋まる。
 *
 * 実測（本当の記憶8件 ＋ 会話のかけら40件で引いてみた）:
 *   「コーヒーどうする？」→ 1位「どう？」 2位「どうかな」 3位に本命
 *   6問中3問で、上位にかけらが混ざった
 *
 * AIへ渡せるのは6件なので、そこが「どう？」で埋まるぶん、本当に効く
 * 記憶が届かない。さらに上限（2000件）に達すると、**昨日の雑談が残って
 * 半年前の事実が消える**。
 *
 * どちら側に倒すか
 * ----------------
 * 外すほうの失敗（覚えるべきことを覚えない）は、**本人からは見えない**。
 * 入れるほうの失敗（雑談が1件混ざる）は、見えるし実害も小さい。
 * なので**迷ったら入れる**。ここで弾くのは「どう見ても事実ではない」形
 * だけにしてある。
 *
 * 賢い判定はしない
 * ----------------
 * 「この発言は重要か」をAIに判断させる手もあるが、発言のたびに往復が
 * 増えて、返事が始まるまでの待ち時間になる。ここは形だけを見る。
 * 本当に覚えるべきことは、AI側の道具（mem_add）でも入れられる。
 */

/** 覚えてほしい、と明示する言い方。これが入っていれば無条件で覚える。 */
const ASK_TO_REMEMBER = /(覚え(て|とい|ておい)|記憶し(て|とい)|忘れないで)/;

/**
 * それ自体では意味を持たない相づち・返事。
 *
 * 前後がそろって初めて意味を持つ物なので、1件の記憶として残しても
 * あとから読んで分からない。
 */
const FILLER = new Set([
  "うん", "ううん", "はい", "いいえ", "ok", "okay", "yes", "no",
  "了解", "りょうかい", "わかった", "分かった", "承知", "なるほど",
  "ありがとう", "ありがとうございます", "ありがと", "thanks", "thank you",
  "そう", "そうだね", "そうです", "ちがう", "違う", "だめ", "ダメ",
  "いいね", "いい", "よし", "おけ", "オッケー", "うーん", "えーと",
  "すみません", "ごめん", "よろしく", "お願いします", "おねがいします",
  "できた", "できない", "はいはい", "そのまま", "それで", "次", "つぎ",
]);

/**
 * 相手にやってもらう言い方の終わり。
 *
 * 「〜して」「〜してください」は**指示**であって、本人についての事実では
 * ない。指示から生まれる予定やタスクは、記憶ではなくタスク側に入る。
 */
const IMPERATIVE_TAIL =
  /(して|してくれ|してください|し(て|と)いて|やって|出して|見せて|作って|直して|変えて|消して|戻して|教えて|調べて|送って|書いて|読んで|開いて|止めて|続けて)[。．!！]?$/;

/** 問いかけ。聞いている側なので、本人についての事実ではない。 */
const QUESTION_TAIL = /[?？]$|(か|かな|かね|だっけ|ですか|ますか)[。．]?$/;

/** これだけ短いと、何のことか後から分からない（日本語で4文字未満）。 */
const MIN_LENGTH = 4;

export interface Verdict {
  /** 記憶に入れるか。 */
  keep: boolean;
  /** 入れるときの大事さ（0=ふつう / 2=本人が「覚えて」と言った）。 */
  importance: number;
  /** 実際に保存する文（「覚えておいて」などの前置きは落とす）。 */
  text: string;
  /** 入れなかった理由。画面には出さないが、テストと調査で使う。 */
  why: string;
}

/** 「覚えておいて、〜」の前置きを落として、中身だけにする。 */
function stripRequest(text: string): string {
  const body = text
    .replace(/^(これ(だけ)?|それ)?(は)?[、,]?\s*/, "")
    .replace(/(を)?(覚え(て|とい|ておい)(ね|て|下さい|ください)?|記憶し(て|とい)(ね|下さい|ください)?|忘れないで(ね|下さい|ください)?)[。．!！]?/g, "")
    .replace(/^[、,。．\s]+|[、,\s]+$/g, "")
    .trim();
  // 前置きしか無かった（「覚えておいて」だけ）なら、元の文を返す
  return body.length >= MIN_LENGTH ? body : text.trim();
}

/**
 * 覚える価値があるか。
 *
 * 弾くのは「どう見ても事実ではない」形だけ。判断に迷う物は通す。
 */
export function worthRemembering(raw: string): Verdict {
  const text = (raw || "").trim();
  if (!text) return { keep: false, importance: 0, text, why: "空" };

  /* ① 本人が「覚えて」と言ったら、ほかの条件は全部飛ばす。
        ここを後ろに置くと、「この番号覚えて」が疑問形や命令形の判定に
        引っかかって落ちる。頼まれた物を落とすのがいちばん困る。 */
  if (ASK_TO_REMEMBER.test(text)) {
    return { keep: true, importance: 2, text: stripRequest(text), why: "覚えてと言われた" };
  }

  const flat = text.toLowerCase().replace(/[。．、,!！?？\s]/g, "");
  if (FILLER.has(flat)) {
    return { keep: false, importance: 0, text, why: "相づち" };
  }
  if (text.length < MIN_LENGTH) {
    return { keep: false, importance: 0, text, why: "短すぎて後から分からない" };
  }
  if (QUESTION_TAIL.test(text)) {
    return { keep: false, importance: 0, text, why: "問いかけ（事実ではない）" };
  }
  if (IMPERATIVE_TAIL.test(text)) {
    return { keep: false, importance: 0, text, why: "指示（本人についての事実ではない）" };
  }

  return { keep: true, importance: 0, text, why: "" };
}
