# toolgate.py — 道具の説明書を、その発言に積むかどうか
# =====================================================================
# なぜ要るのか
# ------------
# 会話の system prompt の **79%** が道具の説明書だった（実測: 全体4,360字の
# うち3,464字・27個）。「ありがとう」にも毎回この3,464字を積んでいる。
#
# しかも同じプロンプトの中で「通常の会話・質問では絶対に使わないこと」と
# 書いている。**使うなと言う物の説明を、毎回3,464字ぶん送っている。**
#
# 入力が多いほど、最初の1文字が出るまでの時間も費用も増える。
# 行動を頼まれていない発言では、積まない。
#
# どちら側に倒すか
# ----------------
# 外し過ぎる失敗（頼んだのに道具を使わない）は、利用者から見ると
# 「できるはずのことをやってくれない」になる。積み過ぎる失敗は、
# 少し遅くて少し高いだけ。なので**迷ったら積む**。
#
# ここで外すのは「どう見ても行動の依頼ではない」形だけにしてある。
# さらに、外して間違えたときの逃げ道も残っている——「実行（司令塔）」
# モードでは常に全部の道具が渡る。そちらは画面に見えている。
# =====================================================================

import re
from typing import Tuple

# ── 積む側の合図 ────────────────────────────────────────────────────

# 相手にやってもらう言い方。「〜して」「〜しといて」など。
_IMPERATIVE = re.compile(
    r"(して|しといて|しておいて|してくれ|してください|やって|お願い|"
    r"追加|作って|つくって|送って|入れて|消して|削除|保存|登録|予約|"
    r"調べて|検索|探して|見せて|出して|まとめて|直して|変えて|教えて|"
    # 手元のパソコン・ブラウザへの頼み方。「日誌に書いておいて」「PDFを
    # 読んで」「ブラウザで開いて」が、ここに1つも無く、会話では道具を
    # 積まずに答えていた（そして道具を知らないAIは、推測で答える）
    r"書いて|書いといて|書いておいて|書き足して|読んで|開いて|押して|流して|"
    r"ておいて|といて)"
)

# 本人の持ち物・外の世界。ここに触れる話は、道具が要ることが多い。
_BELONGINGS = re.compile(
    r"(タスク|todo|ToDo|予定|スケジュール|カレンダー|メール|gmail|Gmail|"
    r"通知|リマインド|ファイル|資料|ドキュメント|ノート|メモ|"
    r"Notion|GitHub|Slack|Drive|ドライブ|スプレッドシート|"
    r"天気|ニュース|株価|為替|相場|レート|"
    r"サイト|ページ|URL|リンク|記事|"
    r"画像|写真|スライド|図|グラフ|"
    r"今日|明日|今週|来週|今月|来月|何時|いつ|"
    # 手元のパソコン（ファイル・Obsidian）と、ログインの先にある画面
    r"日誌|Obsidian|obsidian|手元|パソコン|フォルダ|PDF|"
    r"ブラウザ|ポータル|管理画面|社内|ログイン|手順)"
)

# 「何ができる？」「Notionは使える？」の類。
#
# ここを積まないと、モデルは self_check を呼べないまま**推測で**答える。
# 「できます」と言われて押したらできない、が起きる。
#
# 毎回の指示から画面の一覧を外したぶん（guide.prompt_block 参照）、
# ここは外せない——静的な説明を消して調べる道も渡さないと、
# 前より悪くなる。
_CAPABILITY = re.compile(
    r"(何ができ|なにができ|使い方|つかいかた|できること|"
    r"使える|つかえる|対応してる|対応している|"
    r"繋がって|つながって|接続して|連携して|"
    r"設定でき|機能ある|機能は)"
)

# 長い発言は、たいてい込み入った依頼。短い相づちと分ける。
_LONG = 36


def needs_tools(message: str) -> Tuple[bool, str]:
    """道具の説明書を積むか。戻り値は (積むか, 理由)。

    理由を返すのは、外した判断をあとから追えるようにするため。
    「なんとなく道具を使わなかった」を調べられないと直せない。
    """
    text = (message or "").strip()
    if not text:
        return (False, "空")

    if _CAPABILITY.search(text):
        return (True, "できることを聞かれた（self_check で調べる）")
    if _IMPERATIVE.search(text):
        return (True, "やってほしい形")
    if _BELONGINGS.search(text):
        return (True, "持ち物・外の世界の話")
    if len(text) >= _LONG:
        return (True, "長い（込み入った依頼のことが多い）")

    return (False, "短い会話（行動の合図が無い）")


# 道具を積まなかったときに、代わりに1行だけ添える。
#
# 何も言わないと、モデルは「自分は何もできない」と思い込んで
# 「私にはできません」と答えてしまう。**できるができない、ではなく、
# いま渡していないだけ**だと分かるようにしておく。
NO_TOOLS_NOTE = (
    "【補足】タスク追加・予定・メール・検索などの実行を頼まれた場合は、"
    "「実行（司令塔）モードに切り替えてください」と案内すること。"
    "この会話では道具を直接は使えない。"
)
